# Plots the time-frequency misfits of two tracer signals, a common measure in seismology of how
# well two signals match (https://doi.org/10.1111/j.1365-246X.2009.04177.x). The phase misfit and
# the envelope misfit compare the phases and the amplitudes of the signals over time and frequency.
# The obspy package computes them
# (https://docs.obspy.org/tutorial/code_snippets/time_frequency_misfit.html).
import argparse
import csv
import sys
import warnings

import matplotlib.pyplot as plt
import numpy as np
from obspy.signal.tf_misfit import plot_tf_misfits
from scipy.interpolate import interp1d


def misfits(dt, vx, ref):
    """
    Plots the misfits of the signal vx against the reference ref, both sampled at the evenly
    spaced time stamps dt.
    """
    plot_tf_misfits(
        vx, ref, dt=(dt[1] - dt[0]), fmin=(dt[1] - dt[0]), fmax=(dt[-1] - dt[0])
    )


def tracer_extractor(
    file_name, var=0, x=None, y=None, z=None, r=None, t_min=None, t_max=None
):
    """
    Returns the time stamps and the values of variable var of the one tracer the filters select.
    """

    # The file name may lack the .csv extension.
    candidates = [file_name, file_name + ".csv"]
    csvData = None
    for candidate in candidates:
        try:
            with open(candidate, "r") as inputFile:
                csvData = list(csv.reader(inputFile, delimiter=","))
            break
        except FileNotFoundError:
            continue
    if csvData is None:
        raise SystemExit(
            "None of {} exists, please check the file location".format(
                " or ".join(candidates)
            )
        )
    if not csvData:
        raise SystemExit("{} is empty".format(file_name))

    timeIndex = csvData[0].index(" t")
    vxIndex = csvData[0].index(" data(0)") + var
    firstNumberIndex = csvData[0].index("number(0)")
    secondNumberIndex = csvData[0].index(" number(1)")
    positionIndexes = [csvData[0].index(" x(0)"), csvData[0].index(" x(1)")]
    if " x(2)" in csvData[0]:
        positionIndexes.append(csvData[0].index(" x(2)"))

    if z is not None and len(positionIndexes) < 3:
        raise SystemExit(
            'Command line argument "--z" expects three-dimensional data in {}.'.format(
                file_name
            )
        )

    csvData = [row for row in csvData[1:] if row]

    def position_check(a):
        value = True
        if x is not None:
            value = value and abs(float(a[positionIndexes[0]]) - x) < 0.001
        if y is not None:
            value = value and abs(float(a[positionIndexes[1]]) - y) < 0.001
        if z is not None:
            value = value and abs(float(a[positionIndexes[2]]) - z) < 0.001
        if r is not None:
            value = value and int(a[firstNumberIndex]) == r
        if t_min is not None:
            value = value and float(a[timeIndex]) >= t_min
        if t_max is not None:
            value = value and float(a[timeIndex]) <= t_max
        return value

    csvData = [data for data in csvData if position_check(data)]

    # The pair number(0), number(1) identifies a tracer.
    firstNumbers = set([data[firstNumberIndex] for data in csvData])
    secondNumbers = set([data[secondNumberIndex] for data in csvData])

    if len(firstNumbers) == 0:
        raise Exception(
            "Specification was valid for none of the tracers, please check that a tracer exists at the specified position"
        )
    elif len(firstNumbers) > 1 or len(secondNumbers) > 1:
        raise Exception(
            "Specification was valid for more than one tracer, please clarify which you want through use of positions x, y and z"
        )

    dt = []
    vx = []

    for row in csvData:
        dt.append(float(row[timeIndex]))
        vx.append(float(row[vxIndex]))

    dt, vx = zip(*sorted(zip(dt, vx)))

    return np.array(dt), np.array(vx)


def plot_time_frequency_misfits(argv=None):
    """!

    Plots the time-frequency misfits of one variable between two tracer files.

    The inputs are the CSV databases the ExaHyPE 2 tracers write.

    @param argv Argument list to parse. Defaults to sys.argv[1:].
    """

    parser = argparse.ArgumentParser(
        description="Script to convert CSV generated by ExaHyPE2 executions into plots"
    )
    parser.add_argument(
        "--f1",
        dest="file_name1",
        type=str,
        required=True,
        help="Name of the first file to be checked, does not need to contain '.csv'",
    )
    parser.add_argument(
        "--f2",
        dest="file_name2",
        type=str,
        required=True,
        help="Name of the second file to be checked, does not need to contain '.csv'",
    )
    parser.add_argument(
        "--v",
        dest="v",
        type=int,
        required=True,
        help="Index of the variable to be plotted",
    )
    parser.add_argument(
        "--tmax",
        dest="t_max",
        type=float,
        default=None,
        help="Maximal time for which data should be plotted",
    )
    parser.add_argument(
        "--tmin",
        dest="t_min",
        type=float,
        default=None,
        help="Minimal time from which data should be plotted",
    )
    parser.add_argument(
        "--x",
        dest="x",
        type=float,
        default=None,
        help="x position of tracer which should be considered",
    )
    parser.add_argument(
        "--y",
        dest="y",
        type=float,
        default=None,
        help="y position of tracer which should be considered",
    )
    parser.add_argument(
        "--z",
        dest="z",
        type=float,
        default=None,
        help="z position of tracer which should be considered",
    )
    parser.add_argument(
        "--o",
        dest="o",
        type=str,
        default=None,
        help="Name of the output file, if not specified then the output will be shown interactively",
    )
    args = parser.parse_args(argv)

    dt1, vx1 = tracer_extractor(
        args.file_name1,
        var=args.v,
        x=args.x,
        y=args.y,
        z=args.z,
        t_min=args.t_min,
        t_max=args.t_max,
    )
    dt2, vx2 = tracer_extractor(
        args.file_name2,
        var=args.v,
        x=args.x,
        y=args.y,
        z=args.z,
        t_min=args.t_min,
        t_max=args.t_max,
    )

    # The interpolation needs the time stamps of the second file inside those of the first.
    if (min(dt2) < min(dt1)) or (max(dt2) > max(dt1)):
        warnings.warn(
            "The misfit uses only the time stamps of the second file inside the time "
            "interval of the first file.",
            UserWarning,
        )
        dt2, vx2 = zip(
            *(
                (dt, vx)
                for dt, vx in zip(dt2, vx2)
                if (dt >= min(dt1) and dt <= max(dt1))
            )
        )
        dt2 = np.array(dt2)
        vx2 = np.array(vx2)

    interp_func = interp1d(dt1, vx1)
    interpolated_vx1 = interp_func(dt2)

    misfits(dt2, interpolated_vx1, vx2)

    if args.o is not None:
        plt.savefig(args.o)
    else:
        plt.show()


if __name__ == "__main__":
    plot_time_frequency_misfits(sys.argv[1:])
