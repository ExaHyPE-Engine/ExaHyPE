import csv, argparse, sys


def PlotTracer(argv=None):
    """!

    Plot one variable of one tracer over time.

    Reads a CSV trajectory database as written by the action sets in this folder, selects a single
    tracer, and either shows the resulting plot or writes it to a file.

    matplotlib is imported lazily, so that merely importing exahype2.tracer - which every solver
    build script does - does not require matplotlib to be installed.

    @param argv Argument list to parse. Defaults to sys.argv[1:].
    """
    import matplotlib.pyplot as plt

    parser = argparse.ArgumentParser(
        description="Script to convert CSV generated by ExaHyPE2 executions into plots"
    )
    parser.add_argument("--f",    dest="file_name",     type=str,   required=True, help="Name of the file to be checked, does not need to contain '.csv'")
    parser.add_argument("--v",    dest="v",             type=int,   required=True, help="Index of the variable to be plotted")
    parser.add_argument("--name", dest="variable_name", type=str,   default=None,  help="Name of the variable to be plotted")
    parser.add_argument("--tmax", dest="t_max",         type=float, default=None,  help="Maximal time for which data should be plotted")
    parser.add_argument("--tmin", dest="t_min",         type=float, default=None,  help="Minimal time from which data should be plotted")
    parser.add_argument("--x",    dest="x",             type=float, default=None,  help="x position of tracer which should be considered")
    parser.add_argument("--y",    dest="y",             type=float, default=None,  help="y position of tracer which should be considered")
    parser.add_argument("--z",    dest="z",             type=float, default=None,  help="z position of tracer which should be considered")
    parser.add_argument("--o",    dest="o",             type=str,   default=None,  help="name of output file, if not specified then the output will be shown interactively")
    args = parser.parse_args(argv)

    var_name = "Value" if args.variable_name is None else args.variable_name

    # The database is written with the plain file name, but users tend to pass it without the
    # extension, so fall back to appending it.
    candidates = [args.file_name, args.file_name + ".csv"]
    csvData = None
    for candidate in candidates:
        try:
            with open(candidate, "r") as inputFile:
                csvData = list(csv.reader(inputFile, delimiter=","))
            break
        except FileNotFoundError:
            continue
    if csvData is None:
        raise SystemExit(
            "none of {} exists, please make sure that the file is in the specified location".format(
                " or ".join(candidates)
            )
        )
    if not csvData:
        raise SystemExit("{} is empty".format(args.file_name))

    # Extract some metadata about the positions of the various information in the csv file.
    # These should always be the same but it's safer to check.
    header = csvData[0]
    timeIndex = header.index(" t")
    dataIndex = header.index(" data(0)") + args.v
    firstNumberIndex = header.index("number(0)")
    secondNumberIndex = header.index(" number(1)")
    positionIndexes = [header.index(" x(0)"), header.index(" x(1)")]
    if " x(2)" in header:
        positionIndexes.append(header.index(" x(2)"))

    if args.z is not None and len(positionIndexes) < 3:
        raise SystemExit("--z was given but {} holds two-dimensional data".format(args.file_name))

    # Drop the header, plus any trailing blank line the writer may have left behind. Slicing the
    # last row off unconditionally would discard a real snapshot in a file without one.
    csvData = [row for row in csvData[1:] if row]

    # Filter out only the data from tracers at the specified positions
    def position_check(a):
        value = True
        if args.t_min is not None:
            value = value and float(a[timeIndex]) >= args.t_min
        if args.t_max is not None:
            value = value and float(a[timeIndex]) <= args.t_max
        if args.x is not None:
            value = value and float(a[positionIndexes[0]]) == args.x
        if args.y is not None:
            value = value and float(a[positionIndexes[1]]) == args.y
        if args.z is not None:
            value = value and float(a[positionIndexes[2]]) == args.z
        return value

    csvData = [data for data in csvData if position_check(data)]

    # Check how many tracers fit the filter by extracting the total numbers of number(0) and
    # number(1) tuples that exist with the filter.
    # The {number(0), number(1)} tuples should be unique for each tracer, therefore if there
    # exists more than one value for either of these after filtering, there are multiple
    # tracers that correspond to the filter.
    # In the same way if there are none, none of the tracers correspond to the filter.
    checkFirstIndexLength = set([data[firstNumberIndex] for data in csvData])
    checksecondIndexLength = set([data[secondNumberIndex] for data in csvData])

    if len(checkFirstIndexLength) == 0:
        raise Exception(
            "Specification was valid for none of the tracers, please check that a tracer exists at the specified position"
        )
    elif len(checkFirstIndexLength) > 1 or len(checksecondIndexLength) > 1:
        raise Exception(
            "Specification was valid for more than one tracer, please clarify which you want through use of positions x, y and z"
        )

    # Extract only the data from time and from the required value
    dt = []
    y = []

    for row in csvData:
        dt.append(float(row[timeIndex]))
        y.append(float(row[dataIndex]))

    # Sort this data in the direction of increasing time
    dt, y = zip(*sorted(zip(dt, y)))

    plt.plot(
        dt,
        y,
        color="b",
        linestyle="dashed",
        marker="o",
        label=var_name + " as a function of time",
    )

    plt.xticks(rotation=25)
    plt.xlabel("t")
    plt.ylabel(var_name)
    plt.title(var_name + " as a function of time", fontsize=20)
    plt.grid()
    plt.legend()

    if args.o is not None:
        plt.savefig(args.o)
    else:
        plt.show()


if __name__ == "__main__":
    PlotTracer(sys.argv[1:])
