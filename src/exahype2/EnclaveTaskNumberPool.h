#pragma once

#include "tarch/multicore/BooleanSemaphore.h"

#include <atomic>
#include <queue>

namespace exahype2 {
  class EnclaveTaskNumberPool;
} // namespace exahype2

class exahype2::EnclaveTaskNumberPool {
public:
  explicit EnclaveTaskNumberPool(int refillSize = 16384);
  ~EnclaveTaskNumberPool() = default;

  int getNext();
  void release(int number);
  void reset(int size = 0);

  int sizeInPool(); // Numbers available in the pool
  int sizeInGenerated(); // Total numbers generated by the pool
  int sizeInUse(); // Numbers that are handed out

private:
  const int                           _refillSize;
  std::atomic<int>                    _counter;
  std::queue<int>                     _numberPool;
  tarch::multicore::BooleanSemaphore  _semaphore;

  void refillPool();
};
